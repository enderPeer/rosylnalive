<#
.SYNOPSIS
    Generates build/Toolchain.g.props from tools/bootstrap/toolchain.json, so MSBuild sees the same pins.

.DESCRIPTION
    toolchain.json holds every pin (DataRootAndToolchain contract). Builds that need a tool (for example the shader
    build calling DXC) read $(LrmDxcExe) and $(LrmDxcVersionOutput) from this file instead of repeating a path or a
    version. Paths are rooted at $(LrmData), which this file also resolves (the LrmData property, else LRM_DATA, else
    the dataRoot in toolchain.json, published as $(LrmDefaultData)). -Check exits 1 when the committed file is out of
    date (CI codegen diff).
#>
[CmdletBinding()]
param([switch]$Check)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repo = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path
$t = Get-Content -Raw -LiteralPath (Join-Path $PSScriptRoot 'toolchain.json') | ConvertFrom-Json
function Escape([string]$s) { [System.Security.SecurityElement]::Escape($s).Replace('$', '%24').Replace('@', '%40').Replace(';', '%3B') }

$props = [ordered]@{
    LrmDxcVersion       = $t.dxc.version
    LrmDxcExe           = '$(LrmData)/' + $t.dxc.exe
    LrmDxcVersionOutput = $t.dxc.versionOutput
    LrmVkXmlVersion     = $t.vkxml.version
    LrmVkXml            = '$(LrmData)/' + $t.vkxml.install
    LrmVkHeadersVersion = $t.vkheaders.version
    LrmVkHeaders        = '$(LrmData)/' + $t.vkheaders.install
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.Append("<Project>`n")
[void]$sb.Append("  <!-- GENERATED by tools/bootstrap/gen-toolchain-props.ps1 from tools/bootstrap/toolchain.json. Do not edit. -->`n")
# The data root has one source, toolchain.json's dataRoot; LrmData resolves before any pin uses it.
[void]$sb.Append("  <PropertyGroup>`n")
[void]$sb.Append("    <!-- DataRootAndToolchain: the LrmData property, else LRM_DATA, else dataRoot from toolchain.json. -->`n")
[void]$sb.Append("    <LrmDefaultData>$(Escape $t.dataRoot)</LrmDefaultData>`n")
[void]$sb.Append("    <LrmData Condition=`"'`$(LrmData)' == ''`">`$(LRM_DATA)</LrmData>`n")
[void]$sb.Append("    <LrmData Condition=`"'`$(LrmData)' == ''`">`$(LrmDefaultData)</LrmData>`n")
[void]$sb.Append("  </PropertyGroup>`n")
[void]$sb.Append("  <PropertyGroup>`n")
foreach ($k in $props.Keys) {
    $v = [string]$props[$k]
    # Keep the $(LrmData) prefix live; escape everything else.
    $value = if ($v.StartsWith('$(LrmData)/')) { '$(LrmData)/' + (Escape $v.Substring(11)) } else { Escape $v }
    [void]$sb.Append("    <$k>$value</$k>`n")
}
[void]$sb.Append("  </PropertyGroup>`n</Project>`n")
$want = $sb.ToString()

$path = Join-Path $repo 'build/Toolchain.g.props'
$have = if (Test-Path -LiteralPath $path) { [IO.File]::ReadAllText($path).Replace("`r`n", "`n") } else { $null }
if ($Check) {
    if ($have -ne $want) { Write-Host 'error: build/Toolchain.g.props is out of date; run pwsh tools/bootstrap/gen-toolchain-props.ps1' -ForegroundColor Red; exit 1 }
    Write-Host 'toolchain props: up to date'
}
elseif ($have -ne $want) {
    [IO.File]::WriteAllText($path, $want, [Text.UTF8Encoding]::new($false))
    Write-Host 'wrote build/Toolchain.g.props'
}
else { Write-Host 'toolchain props: up to date' }
