/// Writes the generated F# files (LF endings, deterministic order):
///   - Vk.g.fs: constants, basetypes, handles, enums, bitmasks, inline arrays, structs and unions, funcpointer and
///     command delegates;
///   - VkCommands.g.fs: the global, instance and device dispatch tables with their wrappers;
///   - VkMeta.g.fs: what was bound, with the generator's own C layout of every struct.
module Lrm.Tools.VkGen.Emit

open System
open System.Text
open Lrm.Tools.VkGen.Registry
open Lrm.Tools.VkGen.Bind

type private W() =
    let sb = StringBuilder()
    member _.Line(s: string) = sb.Append(s).Append('\n') |> ignore
    member this.Blank() = this.Line ""
    member _.Text = sb.ToString()

let private header (m: Model) (what: string) =
    [
        "// <auto-generated>"
        sprintf
            "// %s, generated by tools/vkgen from vk.xml (VK_HEADER_VERSION %d) and tools/vkgen/bindings.json."
            what
            m.Registry.HeaderVersion
        "// Do not edit. Regenerate with: dotnet run --project tools/vkgen/Lrm.Tools.VkGen -c Release"
        "// </auto-generated>"
    ]

/// XML-doc text: no angle brackets or ampersands.
let private doc (s: string) =
    s.Replace("&", "and").Replace("<", "(").Replace(">", ")")

let private providerText =
    function
    | Core(a, b) -> sprintf "Vulkan %d.%d" a b
    | Ext(n, _) -> n

let private enumLiteral (e: BEnum) (v: int64) =
    if e.Bits64 then sprintf "0x%016XUL" (uint64 v)
    elif e.IsBitmask then sprintf "0x%08Xu" (uint32 v)
    else sprintf "%d" (int32 v)

/// Arrays and structs in one dependency order: an array after its element struct, a struct after the structs and
/// arrays it holds by value. Ties go by name.
let private layoutOrder (m: Model) : Choice<BArray, BStruct> list =
    let structNames = m.Structs |> List.map (fun s -> s.Def.Name) |> set

    let arrayDeps (a: BArray) =
        if structNames.Contains a.ElementFs then
            [ "s:" + a.ElementFs ]
        else
            []

    let structDeps (s: BStruct) =
        [
            for f in s.Fields do
                match f.Kind with
                | KArray _ -> yield "a:" + f.FsType
                | KStruct -> yield "s:" + f.FsType
                | _ -> ()
        ]
        |> List.distinct

    let nodes =
        [
            for a in m.Arrays -> "a:" + a.Name, Choice1Of2 a, arrayDeps a
            for s in m.Structs -> "s:" + s.Def.Name, Choice2Of2 s, structDeps s
        ]

    let byKey = nodes |> List.map (fun (k, v, d) -> k, (v, d)) |> dict
    let placed = Collections.Generic.HashSet<string>(StringComparer.Ordinal)

    let pending =
        Collections.Generic.SortedSet<string>(byKey.Keys, StringComparer.Ordinal)

    let result = ResizeArray()

    // Sort keys by their name part so arrays and structs interleave alphabetically.
    let nameOf (k: string) = k.Substring 2

    while pending.Count > 0 do
        let ready =
            pending
            |> Seq.filter (fun k -> snd byKey[k] |> List.forall placed.Contains)
            |> Seq.sortBy (fun k -> nameOf k, k)
            |> Seq.tryHead

        match ready with
        | Some k ->
            pending.Remove k |> ignore
            placed.Add k |> ignore
            result.Add(fst byKey[k])
        | None -> failwithf "layout dependency cycle: %s" (String.concat ", " pending)

    List.ofSeq result

let private delegateSignature (ps: (string * string) list) (ret: string) =
    match ps with
    | [] -> sprintf "delegate of unit -> %s" ret
    | ps -> sprintf "delegate of %s -> %s" (ps |> List.map (fun (n, t) -> n + ": " + t) |> String.concat " * ") ret

let private commandText (c: Command) =
    sprintf
        "%s %s(%s)"
        (if c.Return.Pointers > 0 then
             c.Return.TypeName + "*"
         else
             c.Return.TypeName)
        c.Name
        (c.Params |> List.map _.Text |> String.concat ", ")

/// Vk.g.fs.
let types (m: Model) : string =
    let w = W()

    for l in header m "Vulkan types and command delegates" do
        w.Line l

    w.Line(sprintf "namespace %s" m.Bindings.Namespace)
    w.Blank()
    w.Line "#nowarn \"9\""
    w.Blank()
    w.Line "open System"
    w.Line "open System.Runtime.CompilerServices"
    w.Line "open System.Runtime.InteropServices"
    w.Blank()

    // ---- constants ----
    w.Line "/// API constants from vk.xml that bound types or bound features use, and the constants of the bound"
    w.Line "/// extensions (name and spec version)."
    w.Line "[<RequireQualifiedAccess>]"
    w.Line "module VkConst ="
    w.Line "    /// VK_HEADER_VERSION of the vk.xml this binding was generated from."
    w.Line "    [<Literal>]"
    w.Line(sprintf "    let VK_HEADER_VERSION = %d" m.Registry.HeaderVersion)

    for (k, literal) in m.Constants do
        w.Blank()
        w.Line(sprintf "    /// %s %s = %s" k.CType k.Name k.Value)
        w.Line "    [<Literal>]"
        w.Line(sprintf "    let %s = %s" k.Name literal)

    for (n, literal) in m.ExtensionConstants do
        w.Blank()
        w.Line "    [<Literal>]"
        w.Line(sprintf "    let %s = %s" n literal)

    w.Blank()

    // ---- basetypes ----
    for (n, u) in m.Basetypes do
        let fs, _, _ = scalars[u]
        w.Line(sprintf "/// typedef %s %s." u n)
        w.Line(sprintf "type %s = %s" n fs)
        w.Blank()

    // ---- handles ----
    for (n, dispatchable) in m.Handles do
        let field, zero, macro =
            if dispatchable then
                "nativeint", "0n", "VK_DEFINE_HANDLE: a pointer"
            else
                "uint64", "0UL", "VK_DEFINE_NON_DISPATCHABLE_HANDLE: 64 bits"

        w.Line(
            sprintf "/// %s, a %s handle (%s)." n (if dispatchable then "dispatchable" else "non-dispatchable") macro
        )

        w.Line(sprintf "[<Struct; StructLayout(LayoutKind.Sequential); VkHandle(\"%s\", %b)>]" n dispatchable)
        w.Line(sprintf "type %s =" n)
        w.Line(sprintf "    val Handle: %s" field)
        w.Line "    new(h) = { Handle = h }"
        w.Line "    /// VK_NULL_HANDLE."
        w.Line(sprintf "    static member Null = %s %s" n zero)
        w.Line(sprintf "    member this.IsNull = this.Handle = %s" zero)
        w.Line(sprintf "    override this.ToString() = sprintf \"%s(0x%%x)\" this.Handle" n)
        w.Blank()

    // ---- enums ----
    for e in m.Enums do
        let width =
            if e.Bits64 then "64-bit bitmask"
            elif e.IsBitmask then "32-bit bitmask"
            else "32-bit enum"

        w.Line(sprintf "/// %s (%s)." e.Name width)

        if e.IsBitmask then
            w.Line(sprintf "[<Flags; VkEnum(\"%s\")>]" e.Name)
        else
            w.Line(sprintf "[<VkEnum(\"%s\")>]" e.Name)

        w.Line(sprintf "type %s =" e.Name)

        for (n, v) in e.Members do
            w.Line(sprintf "    | %s = %s" n (enumLiteral e v))

        w.Blank()

    // ---- bitmasks and aliases of enums ----
    for (n, target) in m.Bitmasks do
        w.Line(sprintf "/// %s: the bits of a %s." n target)
        w.Line(sprintf "type %s = %s" n target)
        w.Blank()

    let structNames = m.Structs |> List.map (fun s -> s.Def.Name) |> set

    let enumAliases, structAliases =
        m.Aliases |> List.partition (fun (_, t) -> not (structNames.Contains t))

    for (n, t) in enumAliases do
        w.Line(sprintf "/// %s is an alias of %s." n t)
        w.Line(sprintf "type %s = %s" n t)
        w.Blank()

    // ---- arrays and structs ----
    for item in layoutOrder m do
        match item with
        | Choice1Of2 a ->
            w.Line(
                sprintf
                    "/// %s[%d], an inline array of %d bytes. ToArray() copies it out; MemoryMarshal.CreateSpan over e0 and %d elements writes it."
                    a.ElementC
                    a.Count
                    a.Size
                    a.Count
                |> doc
            )

            w.Line(sprintf "[<Struct; InlineArray(%d); VkArray(\"%s\", %d)>]" a.Count a.ElementC a.Count)
            w.Line(sprintf "type %s =" a.Name)
            w.Line(sprintf "    val mutable e0: %s" a.ElementFs)
            w.Line(sprintf "    /// The %d elements, copied out." a.Count)
            w.Line(sprintf "    member this.ToArray() : %s[] =" a.ElementFs)
            w.Line "        let mutable copy = this"
            w.Line(sprintf "        MemoryMarshal.CreateReadOnlySpan(&copy.e0, %d).ToArray()" a.Count)
            w.Blank()
        | Choice2Of2 s ->
            let kind = if s.Def.IsUnion then "union" else "struct"

            let extends =
                match s.Def.Extends with
                | [] -> ""
                | xs -> sprintf " Extends %s." (String.concat ", " xs)

            w.Line(
                sprintf "/// %s (%s, %d bytes, %d-byte aligned on x64).%s" s.Def.Name kind s.Size s.Align extends
                |> doc
            )

            if s.Def.IsUnion then
                w.Line(
                    sprintf
                        "[<Struct; StructLayout(LayoutKind.Explicit, Size = %d); VkUnion(\"%s\")>]"
                        s.Size
                        s.Def.Name
                )
            else
                w.Line(sprintf "[<Struct; StructLayout(LayoutKind.Sequential); VkStruct(\"%s\")>]" s.Def.Name)

            w.Line(sprintf "type %s =" s.Def.Name)

            for f in s.Fields do
                let notes =
                    [
                        match f.Decl.Len with
                        | Some l -> yield "len " + l
                        | None -> ()
                        if not f.Decl.Optional.IsEmpty && List.head f.Decl.Optional = "true" then
                            yield "optional"
                    ]

                let suffix =
                    match notes with
                    | [] -> ""
                    | ns -> sprintf " (%s)" (String.concat ", " ns)

                w.Line(sprintf "    /// %s%s" f.Decl.Text suffix |> doc)

                if s.Def.IsUnion then
                    w.Line "    [<FieldOffset(0)>]"

                w.Line(sprintf "    val mutable %s: %s" f.FsName f.FsType)

            match s.SType with
            | Some(name, _) ->
                w.Line(sprintf "    /// %s." name)
                w.Line(sprintf "    static member StructureType = VkStructureType.%s" name)
                w.Line(sprintf "    /// A zeroed %s with sType set." s.Def.Name)
                w.Line(sprintf "    static member Create() : %s =" s.Def.Name)
                w.Line(sprintf "        let mutable s = %s()" s.Def.Name)
                w.Line(sprintf "        s.sType <- VkStructureType.%s" name)
                w.Line "        s"
            | None -> ()

            w.Blank()

    for (n, t) in structAliases do
        w.Line(sprintf "/// %s is an alias of %s." n t)
        w.Line(sprintf "type %s = %s" n t)
        w.Blank()

    // ---- funcpointers ----
    for f in m.FuncPointers do
        w.Line(sprintf "/// %s." f.Text |> doc)
        w.Line(sprintf "[<UnmanagedFunctionPointer(CallingConvention.Winapi); VkFuncPointer(\"%s\")>]" f.Name)

        w.Line(sprintf "type %s = %s" f.Name (delegateSignature f.Params f.Return))
        w.Blank()

    // ---- command delegates ----
    for c in m.Commands do
        w.Line(sprintf "/// %s." (commandText c.Def) |> doc)

        w.Line(sprintf "/// Provided by %s." (c.Providers |> List.map providerText |> String.concat ", "))

        w.Line(sprintf "[<UnmanagedFunctionPointer(CallingConvention.Winapi); VkCommand(\"%s\")>]" c.Def.Name)
        w.Line(sprintf "type PFN_%s = %s" c.Def.Name (delegateSignature c.DelegateParams c.DelegateReturn))
        w.Blank()

    w.Text

let private conversion (fsType: string) =
    match fsType with
    | "uint32" -> "uint32"
    | "unativeint" -> "unativeint"
    | "uint64"
    | "VkDeviceSize" -> "uint64"
    | t -> failwithf "a count of type %s cannot be taken from a span" t

let private wrapperName (command: string) =
    if command.StartsWith "vk" then
        command.Substring 2
    else
        command

let private emitTable (w: W) (m: Model) (level: Level) (className: string) (summary: string list) =
    let cmds = m.Commands |> List.filter (fun c -> c.Level = level)

    for s in summary do
        w.Line("/// " + s)

    w.Line "[<Sealed>]"
    w.Line(sprintf "type %s(load: string -> nativeint) =" className)
    w.Line "    let missing = ResizeArray<string>()"

    for c in cmds do
        w.Line(sprintf "    let _%s: PFN_%s = VkLoad.fn missing load \"%s\"" c.Def.Name c.Def.Name c.Def.Name)

    w.Blank()
    w.Line(sprintf "    /// The %d command names this table binds, in bindings.json order." cmds.Length)
    w.Line "    static member Names: string list ="
    w.Line "        ["

    for c in cmds do
        w.Line(sprintf "            \"%s\"" c.Def.Name)

    w.Line "        ]"
    w.Blank()
    w.Line "    /// The commands for which the loader returned NULL, in bindings.json order."
    w.Line "    member _.Missing: string list = List.ofSeq missing"

    for c in cmds do
        w.Blank()
        w.Line(sprintf "    /// The raw delegate of %s, or null when the loader returned NULL." c.Def.Name)
        w.Line(sprintf "    member _.%s = _%s" c.Def.Name c.Def.Name)
        w.Blank()

        // The wrapper.
        let sigParams =
            c.Wrapper
            |> List.choose (function
                | ByValue(n, t) -> Some(sprintf "%s: %s" n t)
                | InRef(n, t) -> Some(sprintf "%s: inref<%s>" n t)
                | OutRef(n, t) -> Some(sprintf "%s: byref<%s>" n t)
                | SpanIn(n, e, _) -> Some(sprintf "%s: ReadOnlySpan<%s>" n e)
                | SpanOut(n, e, _) -> Some(sprintf "%s: Span<%s>" n e)
                | Raw n -> Some(sprintf "%s: nativeint" n)
                | Count _
                | Allocator _ -> None)

        let returnsResult = not c.SuccessCodes.IsEmpty
        let onlySuccess = c.SuccessCodes = [ "VK_SUCCESS" ]

        let ret =
            if returnsResult && onlySuccess then "unit"
            elif returnsResult then "VkResult"
            else c.DelegateReturn

        w.Line(sprintf "    /// %s." (commandText c.Def) |> doc)

        let shapes =
            [
                for p in c.Wrapper do
                    match p with
                    | Count(n, _, arrays) -> yield sprintf "%s is the length of %s" n (String.concat " and " arrays)
                    | Allocator n -> yield sprintf "%s is NULL" n
                    | _ -> ()
            ]

        if not shapes.IsEmpty then
            w.Line(sprintf "    /// %s." (String.concat "; " shapes))

        if returnsResult then
            if onlySuccess then
                w.Line "    /// Raises VulkanException unless the result is VK_SUCCESS."
            else
                w.Line(
                    sprintf
                        "    /// Returns the result; raises VulkanException unless it is %s."
                        (String.concat ", " c.SuccessCodes)
                )

        w.Line(sprintf "    member _.%s(%s) : %s =" (wrapperName c.Def.Name) (String.concat ", " sigParams) ret)

        w.Line(sprintf "        let f = _%s" c.Def.Name)
        w.Line(sprintf "        if isNull f then raise (VulkanMissingCommandException \"%s\")" c.Def.Name)

        for p in c.Wrapper do
            match p with
            | Count(_, _, first :: rest) ->
                for r in rest do
                    w.Line(sprintf "        if %s.Length <> %s.Length then" r first)

                    w.Line(
                        sprintf
                            "            invalidArg \"%s\" \"%s: %s and %s must have the same length\""
                            r
                            c.Def.Name
                            first
                            r
                    )
            | _ -> ()

        for p in c.Wrapper do
            match p with
            | InRef(n, _)
            | OutRef(n, _) -> w.Line(sprintf "        use %s_ = fixed &%s" (n.Trim('`')) n)
            | SpanIn(n, _, _)
            | SpanOut(n, _, _) -> w.Line(sprintf "        use %s_ = fixed %s" (n.Trim('`')) n)
            | _ -> ()

        let args =
            c.Wrapper
            |> List.map (function
                | ByValue(n, _)
                | Raw n -> n
                | InRef(n, _)
                | OutRef(n, _)
                | SpanIn(n, _, _)
                | SpanOut(n, _, _) -> sprintf "NativePtr.toNativeInt %s_" (n.Trim('`'))
                | Count(_, t, first :: _) -> sprintf "%s %s.Length" (conversion t) first
                | Count(n, _, []) -> failwithf "%s: count %s sizes nothing" c.Def.Name n
                | Allocator _ -> "0n")
            |> String.concat ", "

        let call = sprintf "f.Invoke(%s)" args

        if returnsResult then
            w.Line(sprintf "        let r = %s" call)

            let test =
                c.SuccessCodes
                |> List.map (fun s -> sprintf "r <> VkResult.%s" s)
                |> String.concat " && "

            w.Line(sprintf "        if %s then raise (VulkanException(\"%s\", r))" test c.Def.Name)

            if not onlySuccess then
                w.Line "        r"
        else
            w.Line(sprintf "        %s" call)

    w.Blank()

/// VkCommands.g.fs.
let commands (m: Model) : string =
    let w = W()

    for l in header m "Vulkan dispatch tables" do
        w.Line l

    w.Line(sprintf "namespace %s" m.Bindings.Namespace)
    w.Blank()
    w.Line "#nowarn \"9\""
    w.Blank()
    w.Line "open System"
    w.Line "open Microsoft.FSharp.NativeInterop"
    w.Blank()

    let common =
        [
            "Each command's raw delegate is loaded once, when the table is built; a missing entry point is null and its"
            "wrapper raises VulkanMissingCommandException. A wrapper passes a const T* as inref<T>, a T* as byref<T>,"
            "an array sized by a by-value count as a span (the count is its length), and pins each for the call only;"
            "pAllocator is always NULL. A VkResult outside the command's success codes raises VulkanException. Calls"
            "allocate nothing."
        ]

    emitTable
        w
        m
        Global
        "VkGlobalCommands"
        ([
            "Global commands: no dispatchable handle, loaded through vkGetInstanceProcAddr(NULL, name)."
         ]
         @ common)

    emitTable
        w
        m
        Instance
        "VkInstanceCommands"
        ([
            "Instance-level commands (first parameter a VkInstance or VkPhysicalDevice, and vkGetDeviceProcAddr), loaded"
            "through vkGetInstanceProcAddr(instance, name)."
         ]
         @ common)

    emitTable
        w
        m
        Device
        "VkDeviceCommands"
        ([
            "Device-level commands (first parameter a VkDevice, VkQueue or VkCommandBuffer), loaded through"
            "vkGetDeviceProcAddr(device, name)."
         ]
         @ common)

    w.Text

/// VkMeta.g.fs.
let meta (m: Model) : string =
    let w = W()

    for l in header m "What the Vulkan binding holds" do
        w.Line l

    w.Line(sprintf "namespace %s" m.Bindings.Namespace)
    w.Blank()
    w.Line "/// What tools/vkgen bound from vk.xml, and the generator's own C layout of every struct and union (x64),"

    w.Line
        "/// computed from vk.xml member types. The ABI oracle checks the runtime against the Vulkan headers; tests and"

    w.Line "/// the device check compare the runtime with this table, so three computations have to agree."
    w.Line "[<RequireQualifiedAccess>]"
    w.Line "module VkMeta ="
    w.Line "    /// VK_HEADER_VERSION of the registry."
    w.Line "    [<Literal>]"
    w.Line(sprintf "    let HeaderVersion = %d" m.Registry.HeaderVersion)
    w.Blank()
    w.Line "    /// The highest core version whose enum values and commands are bound."
    w.Line(sprintf "    let CoreVersion = (%d, %d)" (fst m.Bindings.CoreVersion) (snd m.Bindings.CoreVersion))
    w.Blank()
    w.Line "    /// The bound extensions, in bindings.json order."
    w.Line "    let Extensions: VkExtensionMeta list ="
    w.Line "        ["

    for x in m.BoundExtensions do
        w.Line(
            sprintf "            { Name = \"%s\"; Number = %d; Instance = %b }" x.Name x.Number (x.Kind = "instance")
        )

    w.Line "        ]"
    w.Blank()

    let fieldTuple (f: BField) =
        sprintf "\"%s\", %d, %d" f.Decl.Name f.Offset f.Size

    w.Line "    /// Every bound struct and union: sType, the structs it extends, and the generator's layout."
    w.Line "    let Structs: VkStructMeta list ="
    w.Line "        ["

    for s in m.Structs |> List.sortBy (fun s -> s.Def.Name) do
        let stype =
            match s.SType with
            | Some(n, _) -> sprintf "ValueSome VkStructureType.%s" n
            | None -> "ValueNone"

        let extends =
            s.Def.Extends |> List.map (fun x -> "\"" + x + "\"") |> String.concat "; "

        w.Line "            {"
        w.Line(sprintf "                Name = \"%s\"" s.Def.Name)
        w.Line(sprintf "                Type = typeof<%s>" s.Def.Name)
        w.Line(sprintf "                IsUnion = %b" s.Def.IsUnion)
        w.Line(sprintf "                SType = %s" stype)
        w.Line(sprintf "                Extends = [ %s ]" extends)
        w.Line(sprintf "                ReturnedOnly = %b" s.Def.ReturnedOnly)
        w.Line(sprintf "                AllowDuplicate = %b" s.Def.AllowDuplicate)
        w.Line(sprintf "                Size = %d" s.Size)
        w.Line(sprintf "                Align = %d" s.Align)

        w.Line(
            sprintf
                "                Fields = [ %s ]"
                (s.Fields |> List.map (fieldTuple >> sprintf "(%s)") |> String.concat "; ")
        )

        w.Line "            }"

    w.Line "        ]"
    w.Blank()
    w.Line "    /// Every bound command: its dispatch level, what provides it, and its success codes."
    w.Line "    let Commands: VkCommandMeta list ="
    w.Line "        ["

    for c in m.Commands do
        let level =
            match c.Level with
            | Global -> "VkCommandLevel.Global"
            | Instance -> "VkCommandLevel.Instance"
            | Device -> "VkCommandLevel.Device"

        let providers =
            c.Providers
            |> List.map (function
                | Core(a, b) -> sprintf "VkProvider.Core(%d, %d)" a b
                | Ext(n, i) -> sprintf "VkProvider.Extension(\"%s\", %b)" n i)
            |> String.concat "; "

        let success =
            c.SuccessCodes |> List.map (fun s -> "VkResult." + s) |> String.concat "; "

        w.Line "            {"
        w.Line(sprintf "                Name = \"%s\"" c.Def.Name)
        w.Line(sprintf "                Level = %s" level)
        w.Line(sprintf "                Providers = [ %s ]" providers)
        w.Line(sprintf "                SuccessCodes = [ %s ]" success)
        w.Line(sprintf "                Delegate = typeof<PFN_%s>" c.Def.Name)
        w.Line "            }"

    w.Line "        ]"
    w.Blank()
    w.Line "    /// Type aliases (KHR and EXT names) and the type each names."
    w.Line "    let Aliases: (string * System.Type) list ="
    w.Line "        ["

    for (n, _) in m.Aliases do
        w.Line(sprintf "            \"%s\", typeof<%s>" n n)

    w.Line "        ]"
    w.Text
