namespace Lrm.Gpu.Core

open System
open System.IO
open System.Text
open System.Text.Json
open Lrm.Core

/// The catalog generator (KernelAbiAndCatalog contract): reads src/Lrm.Gpu.Core/Catalog/catalog.json and writes
/// src/Lrm.Gpu.Core/Kernels.g.fs and src/Lrm.Shaders/include/lrm_args.g.hlsli. The output is byte-deterministic
/// (UTF-8 without BOM, LF), so CI and the cpu tier check that the committed files equal a fresh generation.
/// Lrm.Shaders.Build runs it (gen-catalog); it lives here so tests can check it without running a tool.
[<RequireQualifiedAccess>]
module CatalogGen =
    /// The catalog schema.
    [<Literal>]
    let Schema = "lrm.catalog/1"

    /// Repo-relative paths of the source and the generated files.
    [<Literal>]
    let CatalogPath = "src/Lrm.Gpu.Core/Catalog/catalog.json"

    [<Literal>]
    let FSharpPath = "src/Lrm.Gpu.Core/Kernels.g.fs"

    [<Literal>]
    let HlslPath = "src/Lrm.Shaders/include/lrm_args.g.hlsli"

    let private header =
        "GENERATED by Lrm.Shaders.Build gen-catalog from "
        + CatalogPath
        + ". Do not edit."

    // ---- parsing ----------------------------------------------------------------------------------------------

    exception private ParseError of string

    let private fail fmt =
        Printf.kprintf (fun s -> raise (ParseError s)) fmt

    let private props (where: string) (allowed: string list) (required: string list) (e: JsonElement) =
        if e.ValueKind <> JsonValueKind.Object then
            fail "%s must be an object" where

        let names = [ for p in e.EnumerateObject() -> p.Name ]

        for n in names do
            if not (List.contains n allowed) then
                fail "%s: unknown property '%s'" where n

        for r in required do
            if not (List.contains r names) then
                fail "%s: missing property '%s'" where r

        if (List.distinct names).Length <> names.Length then
            fail "%s: duplicate property" where

    let private str (where: string) (e: JsonElement) (name: string) =
        match e.TryGetProperty name with
        | true, v when v.ValueKind = JsonValueKind.String -> v.GetString()
        | _ -> fail "%s: '%s' must be a string" where name

    let private strList (where: string) (e: JsonElement) (name: string) =
        match e.TryGetProperty name with
        | true, v when v.ValueKind = JsonValueKind.Array ->
            [
                for x in v.EnumerateArray() do
                    if x.ValueKind <> JsonValueKind.String then
                        fail "%s: '%s' must hold strings" where name

                    yield x.GetString()
            ]
        | false, _ -> []
        | _ -> fail "%s: '%s' must be an array of strings" where name

    let private checkDoc (where: string) (doc: string) =
        if String.IsNullOrWhiteSpace doc then
            fail "%s: the doc is empty" where

        if doc |> Seq.exists (fun c -> c < ' ' || c > '~') then
            fail "%s: the doc must be one line of printable ASCII" where

        if doc.Trim() <> doc then
            fail "%s: the doc has leading or trailing spaces" where

        doc

    let private parseField (kernel: string) (e: JsonElement) : FieldSpec =
        let where = sprintf "kernel %s field" kernel
        props where [ "name"; "type"; "access"; "dtypes"; "alias"; "doc" ] [ "name"; "type"; "doc" ] e
        let name = str where e "name"
        let where = sprintf "kernel %s field %s" kernel name
        let doc = checkDoc where (str where e "doc")

        match str where e "type" with
        | "token" ->
            let access =
                match Access.tryParse (str where e "access") with
                | Some a -> a
                | None -> fail "%s: access must be read, write, readwrite or meta" where

            let dtypes =
                strList where e "dtypes"
                |> List.map (fun d ->
                    match DType.tryParse d with
                    | Some t -> t
                    | None -> fail "%s: unknown dtype '%s'" where d)

            FieldSpec.token name access dtypes (strList where e "alias") doc
        | t ->
            for p in [ "access"; "dtypes"; "alias" ] do
                match e.TryGetProperty p with
                | true, _ -> fail "%s: '%s' applies only to token fields" where p
                | _ -> ()

            match t with
            | "u32" -> FieldSpec.u32 name doc
            | "i32" -> FieldSpec.i32 name doc
            | "f32" -> FieldSpec.f32 name doc
            | other -> fail "%s: unknown type '%s'" where other

    let private parseKernel (e: JsonElement) : KernelSpec =
        props
            "kernel"
            [ "name"; "family"; "doc"; "threads"; "grid"; "fields" ]
            [ "name"; "family"; "doc"; "threads"; "grid"; "fields" ]
            e

        let name = str "kernel" e "name"
        let where = "kernel " + name

        let family =
            match KernelFamily.tryParse (str where e "family") with
            | Some f -> f
            | None -> fail "%s: family must be selftest, basic, matmul or attention" where

        let threads =
            match [ for x in e.GetProperty("threads").EnumerateArray() -> x ] with
            | [ x; y; z ] when [ x; y; z ] |> List.forall (fun v -> v.ValueKind = JsonValueKind.Number) ->
                x.GetInt32(), y.GetInt32(), z.GetInt32()
            | _ -> fail "%s: threads must be three integers" where

        let grid =
            match strList where e "grid" with
            | [ x; y; z ] ->
                let p (s: string) =
                    match GridExpr.parse s with
                    | Ok g -> g
                    | Error err -> fail "%s: %s" where err

                p x, p y, p z
            | _ -> fail "%s: grid must be three formulas" where

        let fields =
            match e.GetProperty "fields" with
            | v when v.ValueKind = JsonValueKind.Array -> [ for f in v.EnumerateArray() -> parseField name f ]
            | _ -> fail "%s: fields must be an array" where

        {
            Name = name
            Family = family
            Source = KernelFamily.directory family + "/" + name + ".hlsl"
            Threads = threads
            Grid = grid
            Fields = fields
            Doc = checkDoc where (str where e "doc")
        }

    /// Parses and validates catalog.json (strict: unknown properties are errors).
    let parse (json: string) : Result<Catalog, string> =
        try
            use doc =
                JsonDocument.Parse(json, JsonDocumentOptions(CommentHandling = JsonCommentHandling.Disallow))

            let r = doc.RootElement
            props "catalog" [ "schema"; "version"; "about"; "kernels" ] [ "schema"; "version"; "kernels" ] r

            if str "catalog" r "schema" <> Schema then
                fail "catalog: schema must be %s" Schema

            let version =
                match r.GetProperty "version" with
                | v when v.ValueKind = JsonValueKind.Number -> v.GetInt32()
                | _ -> fail "catalog: version must be an integer"

            let kernels =
                match r.GetProperty "kernels" with
                | v when v.ValueKind = JsonValueKind.Array -> [ for k in v.EnumerateArray() -> parseKernel k ]
                | _ -> fail "catalog: kernels must be an array"

            Catalog.validate { Version = version; Kernels = kernels }
        with
        | ParseError e -> Error e
        | :? JsonException as e -> Error(sprintf "catalog.json is not valid JSON: %s" e.Message)
        | :? FormatException as e -> Error e.Message
        | :? InvalidOperationException as e -> Error e.Message

    // ---- emitting -----------------------------------------------------------------------------------------------

    let private fsString (s: string) =
        "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\""

    let private dtypeList (ds: DType list) =
        ds |> List.map DType.name |> String.concat ", "

    /// One line describing a field's word.
    let private describe (i: int) (f: FieldSpec) =
        match f.Kind with
        | FieldKind.Token(access, dtypes, alias) ->
            let ds = if dtypes.IsEmpty then "any dtype" else dtypeList dtypes

            let al =
                if alias.IsEmpty then
                    ""
                else
                    "; may alias " + String.concat ", " alias

            sprintf "word %d: token, %s, %s%s. %s" (i + 1) (Access.name access) ds al f.Doc
        | k -> sprintf "word %d: %s. %s" (i + 1) (FieldKind.typeName k) f.Doc

    let private hlslType (k: FieldKind) =
        match k with
        | FieldKind.Token _
        | FieldKind.U32 -> "uint"
        | FieldKind.I32 -> "int"
        | FieldKind.F32 -> "float"

    let private gridText (k: KernelSpec) =
        let x, y, z = k.Grid
        sprintf "(%s, %s, %s)" (GridExpr.print x) (GridExpr.print y) (GridExpr.print z)

    /// lrm_args.g.hlsli: per kernel the argument struct (word 0 lrm_groups_x, then the fields), its numthreads and
    /// whether its grid is linear.
    let emitHlsl (c: Catalog) : string =
        let sb = StringBuilder()
        let line (s: string) = sb.Append(s).Append('\n') |> ignore
        line ("// " + header)
        line (sprintf "// Catalog version %d, Catalog.hash %s." c.Version (Catalog.hash c).Hex)
        line "// Every field is one 32-bit word: tokens and u32 are uint, i32 is int, f32 is float."
        line "#ifndef LRM_ARGS_G_HLSLI"
        line "#define LRM_ARGS_G_HLSLI"
        line ""
        line (sprintf "#define LRM_CATALOG_VERSION %d" c.Version)

        for k in c.Kernels do
            let tx, ty, tz = k.Threads
            line ""
            line (sprintf "// %s (%s): %s" k.Name (KernelFamily.name k.Family) k.Doc)
            line (sprintf "// Grid %s%s." (gridText k) (if k.Linear then ", linear" else ""))
            line (sprintf "struct lrm_args_%s" k.Name)
            line "{"
            line "    uint lrm_groups_x; // word 0: thread groups in x of the physical grid"

            k.Fields
            |> List.iteri (fun i f -> line (sprintf "    %s %s; // %s" (hlslType f.Kind) f.Name (describe i f)))

            line "};"
            line (sprintf "#define LRM_THREADS_%s %d, %d, %d" k.Name tx ty tz)
            line (sprintf "#define LRM_THREADS_X_%s %du" k.Name tx)
            line (sprintf "#define LRM_THREADS_Y_%s %du" k.Name ty)
            line (sprintf "#define LRM_THREADS_Z_%s %du" k.Name tz)
            line (sprintf "#define LRM_LINEAR_%s %d" k.Name (if k.Linear then 1 else 0))

        line ""
        line "#endif // LRM_ARGS_G_HLSLI"
        sb.ToString()

    let private fsType (k: FieldKind) =
        match k with
        | FieldKind.Token _ -> "TensorToken"
        | FieldKind.U32 -> "uint32"
        | FieldKind.I32 -> "int"
        | FieldKind.F32 -> "float32"

    let private fsField (f: FieldSpec) =
        match f.Kind with
        | FieldKind.Token(access, dtypes, alias) ->
            // DType case names are the safetensors names (F32, BF16, ...).
            let ds = dtypes |> List.map (fun d -> "DType." + DType.safetensorsName d)

            let dtypesText =
                if ds.IsEmpty then
                    "[]"
                else
                    "[ " + String.concat "; " ds + " ]"

            let aliasText =
                if alias.IsEmpty then
                    "[]"
                else
                    "[ " + (alias |> List.map fsString |> String.concat "; ") + " ]"

            sprintf
                "FieldSpec.token %s Access.%s %s %s %s"
                (fsString f.Name)
                (match access with
                 | Access.Read -> "Read"
                 | Access.Write -> "Write"
                 | Access.ReadWrite -> "ReadWrite"
                 | Access.Meta -> "Meta")
                dtypesText
                aliasText
                (fsString f.Doc)
        | FieldKind.U32 -> sprintf "FieldSpec.u32 %s %s" (fsString f.Name) (fsString f.Doc)
        | FieldKind.I32 -> sprintf "FieldSpec.i32 %s %s" (fsString f.Name) (fsString f.Doc)
        | FieldKind.F32 -> sprintf "FieldSpec.f32 %s %s" (fsString f.Name) (fsString f.Doc)

    let private familyCase (f: KernelFamily) =
        match f with
        | KernelFamily.Selftest -> "Selftest"
        | KernelFamily.Basic -> "Basic"
        | KernelFamily.Matmul -> "Matmul"
        | KernelFamily.Attention -> "Attention"

    /// Kernels.g.fs: the catalog as data (Kernels.all, KernelId i = all[i]), then per kernel a typed argument record
    /// and a module with Id, Name, encode, decode, grid and dispatch.
    let emitFSharp (c: Catalog) : string =
        let sb = StringBuilder()
        let line (s: string) = sb.Append(s).Append('\n') |> ignore
        line ("// " + header)
        line "namespace Lrm.Gpu.Core"
        line ""
        line "open Lrm.Core"
        line ""

        line
            "/// The kernel catalog (KernelAbiAndCatalog contract), generated from catalog.json: every entry as data, and per"

        line
            "/// kernel a typed argument record with its encoder. Argument word 0 is lrm_groups_x, which Dispatch writes."

        line "[<RequireQualifiedAccess>]"
        line "module Kernels ="
        line "    /// The catalog version."
        line "    [<Literal>]"
        line (sprintf "    let Version = %d" c.Version)
        line ""
        line "    /// Catalog.hash of the catalog this file was generated from."
        line "    [<Literal>]"
        line (sprintf "    let CatalogHashHex = %s" (fsString (Catalog.hash c).Hex))
        line ""
        line "    let private grid (x: string) (y: string) (z: string) ="
        line "        let p (s: string) ="
        line "            match GridExpr.parse s with"
        line "            | Ok g -> g"
        line "            | Error e -> failwith e"
        line ""
        line "        p x, p y, p z"
        line ""
        line "    /// Every entry in catalog order; KernelId i is all[i]."
        line "    let all: KernelSpec[] ="
        line "        [|"

        for k in c.Kernels do
            let tx, ty, tz = k.Threads
            let gx, gy, gz = k.Grid
            line "            {"
            line (sprintf "                Name = %s" (fsString k.Name))
            line (sprintf "                Family = KernelFamily.%s" (familyCase k.Family))
            line (sprintf "                Source = %s" (fsString k.Source))
            line (sprintf "                Threads = (%d, %d, %d)" tx ty tz)

            line (
                sprintf
                    "                Grid = grid %s %s %s"
                    (fsString (GridExpr.print gx))
                    (fsString (GridExpr.print gy))
                    (fsString (GridExpr.print gz))
            )

            line "                Fields ="
            line "                    ["

            for f in k.Fields do
                line ("                        " + fsField f)

            line "                    ]"
            line (sprintf "                Doc = %s" (fsString k.Doc))
            line "            }"

        line "        |]"
        line ""
        line "    /// The catalog as a value."
        line "    let catalog: Catalog = { Version = Version; Kernels = List.ofArray all }"
        line ""
        line "    /// The id of a kernel name."
        line "    let tryFind (name: string) ="
        line "        all |> Array.tryFindIndex (fun k -> k.Name = name) |> Option.map KernelId"

        c.Kernels
        |> List.iteri (fun index k ->
            let p = KernelSpec.pascal k.Name
            let argsType = p + "Args"
            line ""
            line (sprintf "    /// Arguments of %s: %s" k.Name k.Doc)
            line (sprintf "    type %s =" argsType)
            line "        {"

            k.Fields
            |> List.iteri (fun i f ->
                line (sprintf "            /// %s" (describe i f))
                line (sprintf "            %s: %s" (KernelSpec.pascal f.Name) (fsType f.Kind)))

            line "        }"
            line ""

            line (
                sprintf
                    "    /// %s (%s), grid %s%s."
                    k.Name
                    (KernelFamily.name k.Family)
                    (gridText k)
                    (if k.Linear then ", linear" else "")
            )

            line "    [<RequireQualifiedAccess>]"
            line (sprintf "    module %s =" p)
            line (sprintf "        let Id = KernelId %d" index)
            line ""
            line "        [<Literal>]"
            line (sprintf "        let Name = %s" (fsString k.Name))
            line ""
            line "        /// The catalog entry."
            line (sprintf "        let spec () = all[%d]" index)
            line ""
            line "        /// The argument block, word 0 left 0 for Dispatch."
            line (sprintf "        let encode (a: %s) : ArgBlock =" argsType)
            line "            let w = Array.zeroCreate<uint32> ArgBlock.WordCount"

            k.Fields
            |> List.iteri (fun i f ->
                let v = "a." + KernelSpec.pascal f.Name

                let expr =
                    match f.Kind with
                    | FieldKind.Token _ -> v + ".Value"
                    | FieldKind.U32 -> v
                    | FieldKind.I32 -> "ArgBlock.i32Bits " + v
                    | FieldKind.F32 -> "ArgBlock.f32Bits " + v

                line (sprintf "            w[%d] <- %s" (i + 1) expr))

            line "            ArgBlock.OfWords w"
            line ""
            line "        /// The fields of an argument block."
            line (sprintf "        let decode (b: ArgBlock) : %s =" argsType)
            line "            {"

            k.Fields
            |> List.iteri (fun i f ->
                let expr =
                    match f.Kind with
                    | FieldKind.Token _ -> sprintf "TensorToken b[%d]" (i + 1)
                    | FieldKind.U32 -> sprintf "b[%d]" (i + 1)
                    | FieldKind.I32 -> sprintf "b.I32 %d" (i + 1)
                    | FieldKind.F32 -> sprintf "b.F32 %d" (i + 1)

                line (sprintf "                %s = %s" (KernelSpec.pascal f.Name) expr))

            line "            }"
            line ""
            line "        /// The logical grid, from the catalog formula."
            line (sprintf "        let grid (a: %s) : Grid = KernelSpec.gridOf all[%d] (encode a)" argsType index)
            line ""
            line "        /// Records the dispatch."

            line (
                sprintf
                    "        let dispatch (commands: ICommandList) (a: %s) = commands.Dispatch(Id, encode a)"
                    argsType
            ))

        sb.ToString()

    // ---- files --------------------------------------------------------------------------------------------------

    let private utf8 = UTF8Encoding(false)

    /// The generated files for the catalog at `repoRoot`: (repo-relative path, content).
    let outputs (repoRoot: string) : Result<(string * string) list, string> =
        let path = Path.Combine(repoRoot, CatalogPath)

        if not (File.Exists path) then
            Error(sprintf "%s is missing" path)
        else
            match parse (File.ReadAllText(path, utf8)) with
            | Error e -> Error e
            | Ok c -> Ok [ FSharpPath, emitFSharp c; HlslPath, emitHlsl c ]

    /// The generated files that differ from a fresh generation (empty when everything is current).
    let stale (repoRoot: string) : Result<string list, string> =
        outputs repoRoot
        |> Result.map (fun outs ->
            outs
            |> List.filter (fun (rel, content) ->
                let p = Path.Combine(repoRoot, rel)
                not (File.Exists p) || File.ReadAllText(p, utf8) <> content)
            |> List.map fst)

    /// Writes the generated files that differ and returns their paths.
    let write (repoRoot: string) : Result<string list, string> =
        match outputs repoRoot, stale repoRoot with
        | Ok outs, Ok changed ->
            for rel, content in outs do
                if List.contains rel changed then
                    File.WriteAllText(Path.Combine(repoRoot, rel), content, utf8)

            Ok changed
        | Error e, _
        | _, Error e -> Error e
